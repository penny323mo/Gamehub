#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import {
  CATALOG_SCHEMA_VERSION,
  GENERATED_RELATIVE_PATH,
  MANIFEST_RELATIVE_PATH,
  REPO_ROOT,
  loadGameCatalog,
  validateCatalog
} from '../games/catalog.mjs';

const hash = (text) => {
  // Deterministic non-cryptographic cache identity: browser freshness only.
  let value = 0x811c9dc5;
  for (let index = 0; index < text.length; index += 1) {
    value ^= text.charCodeAt(index);
    value = Math.imul(value, 0x01000193);
  }
  return (value >>> 0).toString(36);
};

const syncHubCatalogVersion = (rootDir, token, { checkOnly }) => {
  const indexPath = path.join(rootDir, 'index.html');
  const source = fs.readFileSync(indexPath, 'utf8');
  const pattern = /(games\/catalog\.generated\.js\?v=)[a-z0-9-]+/g;
  const updated = source.replace(pattern, `$1${token}`);
  if (updated === source && !source.includes(`games/catalog.generated.js?v=${token}`)) {
    throw new Error('index.html has no versioned GameCatalog browser script');
  }
  if (checkOnly && updated !== source) return false;
  if (!checkOnly && updated !== source) fs.writeFileSync(indexPath, updated);
  return true;
};

const args = new Set(process.argv.slice(2));
const checkOnly = args.has('--check');
const rootDir = REPO_ROOT;
const catalog = loadGameCatalog({ rootDir, validate: false, checkGenerated: false });
validateCatalog(catalog, { rootDir, checkGenerated: false });

const data = { schemaVersion: CATALOG_SCHEMA_VERSION, games: catalog.games };
const json = JSON.stringify(data);
const catalogToken = `catalog-${hash(json)}`;
const generated = `/* eslint-disable */
/* Generated by scripts/build-game-catalog.mjs. Edit games/manifest.json instead. */
const GAME_CATALOG_JSON = ${JSON.stringify(json)};
const GAME_CATALOG_DATA = Object.freeze(JSON.parse(GAME_CATALOG_JSON));
const GAME_CATALOG_GAMES = Object.freeze(GAME_CATALOG_DATA.games);
const GAME_CATALOG_API = Object.freeze({
    schemaVersion: GAME_CATALOG_DATA.schemaVersion,
    games: GAME_CATALOG_GAMES,
    list() { return GAME_CATALOG_GAMES.slice(); },
    get(id) { return GAME_CATALOG_GAMES.find((game) => game.id === id); },
    launcherEntries() {
        return GAME_CATALOG_GAMES.map((game) => ({
            id: game.id,
            title: game.title,
            subtitle: game.subtitle,
            icon: game.icon,
            iconWebp: game.iconWebp,
            isImage: game.isImage,
            category: game.category,
            playable: game.playable,
            link: game.launchPath
        }));
    },
    targets() {
        return GAME_CATALOG_GAMES.map((game) => ({
            id: game.id,
            testName: game.testName,
            title: game.title,
            entry: game.entry,
            launchPath: game.launchPath,
            route: game.smoke?.route ?? game.launchPath,
            viewport: game.smoke?.viewport,
            playable: game.playable,
            root: game.release?.roots?.find((item) => item.startsWith('games/')) ?? game.release?.roots?.[0] ?? null,
            roots: game.release?.roots?.slice() ?? [],
            release: game.release
        }));
    }
});
globalThis.GAME_CATALOG = GAME_CATALOG_DATA;
globalThis.GameCatalog = GAME_CATALOG_API;
globalThis.gameCatalog = GAME_CATALOG_API;
if (typeof module !== 'undefined' && module.exports) module.exports = { GAME_CATALOG_DATA, GAME_CATALOG_API };
`;

const outputPath = path.join(rootDir, GENERATED_RELATIVE_PATH);
if (checkOnly) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : null;
  const versionCurrent = syncHubCatalogVersion(rootDir, catalogToken, { checkOnly: true });
  if (current !== generated || !versionCurrent) {
    console.error(`${GENERATED_RELATIVE_PATH} is stale; run node scripts/build-game-catalog.mjs`);
    process.exitCode = 1;
  } else {
    console.log(`GameCatalog generated artifact: PASS (${MANIFEST_RELATIVE_PATH} in parity)`);
  }
} else {
  fs.writeFileSync(outputPath, generated);
  syncHubCatalogVersion(rootDir, catalogToken, { checkOnly: false });
  console.log(`Wrote ${GENERATED_RELATIVE_PATH} (${catalog.games.length} games, ${catalogToken})`);
}
