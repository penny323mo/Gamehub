/**
 * 位元組級載入進度。
 *
 * 點解要有呢個：MOBA 同 Empire Royale 都用 `Promise.all` 平行落十幾個 GLB，
 * 而進度係「幾多件完成咗 / 總共幾多件」。平行落嘅時候頻寬係分薄嘅，
 * **冇一件會早早完成**——實測 Fast 3G 之下，MOBA 撳完之後畫面連續 23.6 秒
 * 一個 pixel 都冇變（個字寫住「載入資產…」但個數字一直冇出過），
 * Royale 14.4 秒。個條 bar 由 0 跳去 100。
 *
 * 有字唔等於有交代。玩家分唔清「載緊」同「死咗」——ADR-203 幫 Tower 講過
 * 呢句，呢度係同一個形狀喺另外兩隻遊戲度。
 *
 * 量位元組就冇呢個問題：十四個檔一齊落，每一段 chunk 都會令個總數行前。
 *
 * 用法：
 *     const 進度 = 建位元組進度(jobs.length, (分數, 詳) => { ... });
 *     loader.load(url, onLoad, (e) => 進度.報(url, e.loaded, e.total), onErr);
 *     // 一件落完（或者 cache hit 冇報過 progress）就補一句
 *     進度.完(url, 位元組數);
 */
export function 建位元組進度(件數, 出) {
    const 表 = new Map();   // url -> { 落咗, 全 }
    let 上次 = 0;
    let 上次落咗 = 0;

    const 送 = () => {
        let 落咗 = 0, 已知 = 0, 已知件 = 0, 完咗 = 0;
        for (const v of 表.values()) {
            落咗 += v.落咗;
            if (v.全 > 0) { 已知 += v.全; 已知件++; if (v.落咗 >= v.全) 完咗++; }
        }
        // 未收到 header 嗰啲，用已知嗰啲嘅平均去估。估得唔準冇所謂——
        // 要緊嘅係個數會**一路行**，唔係企喺 0 度。
        const 平均 = 已知件 ? 已知 / 已知件 : 0;
        const 估總 = 已知 + Math.max(0, 件數 - 已知件) * 平均;
        // **唔知總數就唔好報一個數。** 冇 `Content-Length` 嘅伺服器會令
        // `e.total` 係 0；照計嘅話個分數永遠係 0，條 bar 就變返「卡死喺 0
        // 然後跳去 100」——即係我哋想修嗰個病。呢種時候寧願報 null，
        // 叫個 UI 出一條唔知幾耐嘅（indeterminate）bar，加埋落咗幾多 MB。
        // 落咗幾多 MB 係一定知嘅，而佢逐秒都郁——夠交代。
        let 分 = 已知件 > 0 && 估總 > 0 ? Math.max(0, Math.min(1, 落咗 / 估總)) : null;
        // 估數會隨住 header 陸續到而變，唔夾硬鎖住嘅話條 bar 會倒退。
        // **一條會倒退嘅進度條比冇進度條更嚇人。**
        if (分 !== null) { if (分 < 上次) 分 = 上次; 上次 = 分; }
        上次落咗 = 落咗;
        出(分, { 落咗, 估總, 完咗, 件數 });
    };

    return {
        報(url, 落咗, 全) { 表.set(url, { 落咗: 落咗 || 0, 全: 全 || 表.get(url)?.全 || 0 }); 送(); },
        完(url, 大細) {
            const 舊 = 表.get(url);
            const n = 大細 || 舊?.全 || 舊?.落咗 || 0;
            表.set(url, { 落咗: n, 全: n });
            送();
        },
        // 全部落完：解碼／建場景仲有排，但落嘅部分係真係 100%。
        齊() { 上次 = 1; 出(1, { 落咗: 上次落咗, 估總: 上次落咗, 完咗: 件數, 件數 }); },
    };
}
